const app = document.querySelector('#app')

let currentChapter = 0
let currentPage = 0

function renderHome() {
  app.innerHTML = `
    <main class="container">
      <h1>حكاية الأسرار القديمة</h1>
      <p class="subtitle">رواية من عشرين فصلاً</p>
      <div class="book">
        <h2>مرحباً بك في عالم الحكاية</h2>
        <p>رحلة مليئة بالغموض والصداقة والبحث عن الحقيقة.</p>
        <button id="start">ابدأ القراءة</button>
      </div>
      <h2>فصول الرواية</h2>
      <div class="chapter-list">
        ${chapters.map((chapter, index) => `
          <button class="chapter-button" data-chapter="${index}">
            الفصل ${index + 1}: ${chapter.title}
          </button>
        `).join('')}
      </div>
    </main>
  `

  document.querySelector('#start').addEventListener('click', () => {
    currentChapter = 0
    currentPage = 0
    renderPage()
  })

  document.querySelectorAll('.chapter-button').forEach(button => {
    button.addEventListener('click', () => {
      currentChapter = Number(button.dataset.chapter)
      currentPage = 0
      renderPage()
    })
  })
}

function renderPage() {
  const chapter = chapters[currentChapter]
  const totalPages = chapter.pages.length

  app.innerHTML = `
    <main class="container">
      <button id="home" class="secondary">الرئيسية</button>
      <div class="reading-card">
        <p class="subtitle">الفصل ${currentChapter + 1} من ${chapters.length}</p>
        <h1>${chapter.title}</h1>
        <div class="story-text">${chapter.pages[currentPage].replace(/\n\n/g, '<br><br>')}</div>
        <p class="page-number">الصفحة ${currentPage + 1} من ${totalPages}</p>
        <div class="navigation">
          <button id="previous" ${currentPage === 0 && currentChapter === 0 ? 'disabled' : ''}>السابق</button>
          <button id="next">${currentPage === totalPages - 1 && currentChapter === chapters.length - 1 ? 'الرئيسية' : 'التالي'}</button>
        </div>
      </div>
    </main>
  `

  document.querySelector('#home').addEventListener('click', renderHome)

  document.querySelector('#previous').addEventListener('click', () => {
    if (currentPage > 0) {
      currentPage--
    } else if (currentChapter > 0) {
      currentChapter--
      currentPage = chapters[currentChapter].pages.length - 1
    }
    renderPage()
  })

  document.querySelector('#next').addEventListener('click', () => {
    if (currentPage < totalPages - 1) {
      currentPage++
    } else if (currentChapter < chapters.length - 1) {
      currentChapter++
      currentPage = 0
    } else {
      renderHome()
      return
    }
    renderPage()
  })
}

